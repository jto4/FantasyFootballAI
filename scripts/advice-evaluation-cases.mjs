export function adviceContext(prompt) {
  const block = prompt.match(/<untrusted_advice_data>\n([\s\S]*?)\n<\/untrusted_advice_data>/)?.[1];
  if (!block) throw new Error('Missing evaluation context.');
  const context = JSON.parse(block);
  return context.metricProfiles ? { ...context, ...expandCompactAdviceEvidence(context) } : context;
}

export function validatedEvaluationAnswer(text, context) {
  const parsed = JSON.parse(text.replace(/^\s*```(?:json)?\s*/i, '').replace(/\s*```\s*$/, ''));
  const answer = validateAdviceAssessment(
    parsed,
    [...context.metrics, ...context.players.flatMap((p) => p.metrics)],
    context.sources.map((s) => s.id),
    context.allowedPlayerIds,
    context.request.mode === 'betting',
  );
  if (
    context.request.mode === 'lineup' &&
    ['recommend', 'lean'].includes(context.decisionPolicy.maximumVerdict) &&
    ['recommend', 'lean'].includes(answer.verdict)
  )
    if (context.startSit)
      validateStartSitAssessment(answer, {
        candidates: context.candidates,
        players: context.players,
        startSit: context.startSit,
      });
    else
      validateLineupAssessment(
        answer,
        {
          mode: 'lineup',
          candidates: context.candidates,
          players: context.players,
          lineup: context.lineup,
        },
        context.league.settings.roster_positions,
      );
  return answer;
}

export function evaluationValidationFailure(error) {
  if (error?.name === 'SyntaxError') return 'invalid-json';
  const message = typeof error?.message === 'string' ? error.message : '';
  if (/answer structure/.test(message)) return 'invalid-schema';
  if (/unsupported player/.test(message)) return 'player-reference';
  if (/unsupported evidence/.test(message)) return 'evidence-reference';
  if (/unsupported numbers|numerical claim|link/.test(message))
    return 'unsupported-numeric-text-or-link';
  if (/lacked numerical support/.test(message)) return 'missing-numerical-support';
  if (/complete legal lineup/.test(message)) return 'lineup-selection';
  if (/visible estimates for the changed players/.test(message)) return 'missing-lineup-tradeoff';
  return 'invalid-contract';
}

/** Classify only fixed local adapter errors; never return arbitrary provider diagnostics. */
export function evaluationProviderFailure(error) {
  if (error instanceof SignedInCodexError || error instanceof SignedInAIError) {
    if (error instanceof SignedInCodexError && error.code === 'invalid-response') {
      const safeReasons = new Set([
        'malformed-event',
        'event-limit',
        'after-completion',
        'unexpected-event',
        'unexpected-item',
        'native-item-error',
        'answer-before-turn',
        'multiple-answers',
        'empty-answer',
        'native-failure',
        'missing-final',
        'nonzero-exit',
      ]);
      if (safeReasons.has(error.protocolFailure)) return `provider-native-${error.protocolFailure}`;
    }
    const codes = {
      'limit-reported': 'provider-limit-reported',
      'invalid-response': 'provider-native-invalid-response',
      'budget-reached': 'provider-budget-reached',
      'unsupported-cli': 'provider-unverified-cli-version',
      'isolation-unavailable': 'provider-isolation-unavailable',
    };
    return codes[error.code] ?? 'generation-or-validation-failed';
  }
  if (error?.name === 'TimeoutError') return 'provider-timeout';
  if (error?.name === 'AbortError') return 'evaluation-cancelled';
  const message = typeof error?.message === 'string' ? error.message : '';
  if (/^AI CLI exited with (?:\d+|no status)\.$/.test(message)) return 'provider-exit';
  if (message === 'Could not start the configured AI CLI. Confirm it is installed and executable.')
    return 'provider-startup';
  if (message === 'AI CLI response exceeded the size limit.') return 'provider-response-too-large';
  if (message === 'AI CLI returned no text.') return 'provider-empty-response';
  return 'generation-or-validation-failed';
}

export function gradeAdviceEvaluation(testCase, result, passes) {
  const failures = [];
  if (!isAdviceResult(result)) failures.push('invalid-result');
  if (passes.length !== 2) failures.push('missing-analysis-or-review');
  // Score the raw final model answer too: a guard that fixes the answer must not
  // conceal weak model judgment. First-pass failures are reported independently.
  const final = passes[1]?.answer;
  if (!final) failures.push('invalid-reviewed-answer');
  for (const [name, answer] of [
    ['model', final],
    ['saved', result.assessment],
  ]) {
    if (!answer) continue;
    if (!testCase.expected.verdicts.includes(answer.verdict))
      failures.push(`${name}-wrong-verdict`);
    if (
      testCase.expected.picks &&
      [...answer.recommendedPlayerIds].sort().join('|') !==
        [...testCase.expected.picks].sort().join('|')
    )
      failures.push(`${name}-wrong-players`);
    const perception = testCase.expected.perception ?? { tone: 'unknown' };
    if (answer.perception.tone !== perception.tone)
      failures.push(
        `${name}-${perception.tone === 'unknown' ? 'unsupported-perception' : 'wrong-perception-tone'}`,
      );
    if (perception.sourceIds?.some((id) => !answer.perception.sourceIds.includes(id)))
      failures.push(`${name}-missing-perception-sources`);
    // Accept equivalent numerical reasoning, while keeping every metric in a
    // chosen comparison visible. A roster-relative alternative must substantiate
    // all candidates versus their actual starters, not just cite one big total.
    const supportAlternatives = testCase.expected.supportMetricAlternatives ?? [
      testCase.expected.supportMetrics ??
        (testCase.expected.metric ? [testCase.expected.metric] : []),
    ];
    if (
      !supportAlternatives.some((ids) =>
        ids.every((id) =>
          answer.reasons.some(
            (reason) => reason.metricIds.includes(id) && reason.text.includes(`{{${id}}}`),
          ),
        ),
      )
    )
      failures.push(`${name}-missing-decision-support`);
  }
  if (
    testCase.expected.feedStatus &&
    result.perceptionEvidence?.feedStatus !== testCase.expected.feedStatus
  )
    failures.push('wrong-feed-status');
  if (
    testCase.expected.perception?.tone !== undefined &&
    testCase.expected.perception.tone !== 'unknown' &&
    (result.perceptionEvidence?.feedStatus !== 'current' ||
      testCase.expected.perception.sourceIds.some(
        (id) =>
          !result.perceptionEvidence.headlines.some((headline) => headline.sourceId === id) ||
          !result.sources.some((source) => source.id === id && source.status === 'available'),
      ))
  )
    failures.push('unsupported-current-media');
  if (testCase.expected.metric) {
    const metric = [...result.metrics, ...result.players.flatMap((p) => p.metrics)].find(
      (m) => m.id === testCase.expected.metric,
    );
    if (!metric || Math.abs(metric.value - testCase.expected.value) > 1e-8)
      failures.push('wrong-computed-value');
  }
  for (const [id, value] of Object.entries(testCase.expected.fixedMetrics ?? {})) {
    const metric = [...result.metrics, ...result.players.flatMap((p) => p.metrics)].find(
      (m) => m.id === id,
    );
    if (!metric || Math.abs(metric.value - value) > 1e-8)
      failures.push('wrong-fixed-forecast-value');
  }
  if (result.confidence.score < 0 || result.confidence.score > 100)
    failures.push('invalid-confidence');
  if (
    testCase.automaticForecast &&
    result.players.some(
      (player) =>
        !player.projectionMethod?.startsWith('rolling-') ||
        player.projectedPoints === undefined ||
        !player.metrics.some((m) => m.id === `${player.id}:forecast-lower`) ||
        !player.metrics.some((m) => m.id === `${player.id}:forecast-mae`),
    )
  )
    failures.push('missing-automatic-forecast-evidence');
  if (
    testCase.expected.maximumConfidence !== undefined &&
    result.confidence.score > testCase.expected.maximumConfidence
  )
    failures.push('unsupported-confidence');
  return {
    passed: failures.length === 0,
    failures,
    firstPassValid: Boolean(passes[0]?.answer),
    ...(passes[0]?.validationFailure ? { firstPassFailure: passes[0].validationFailure } : {}),
    ...(passes[1]?.validationFailure ? { reviewedFailure: passes[1].validationFailure } : {}),
  };
}

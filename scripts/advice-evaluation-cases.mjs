function automaticEvaluationData(catalog) {
  const teams = ['BUF', 'MIA', 'KC', 'NYJ', 'NE', 'LA', 'SF', 'SEA'];
  const participants = definitions.map(([id, , , points]) => ({ ...catalog.get(id), points }));
  for (const team of teams.slice(2))
    for (const position of ['QB', 'RB', 'WR'])
      participants.push({
        gsisId: `gsis-${team}-${position}`,
        name: `Fictional ${team} ${position}`,
        nflTeam: team,
        position,
        points: 10,
      });
  const data = {
    season: 2026,
    games: [],
    players: [],
    market: [],
    warnings: [],
    sources: ['games', 'stats-2024', 'stats-2025', 'stats-2026'].map((id) => ({
      id,
      name: `Fictional ${id}`,
      status: 'available',
      retrievedAt: stamp,
    })),
  };
  for (const season of [2024, 2025, 2026])
    for (let week = 1; week <= 18; week++) {
      if (week === 10) continue;
      const complete = season < 2026 || week < 5;
      for (let pair = 0; pair < 4; pair++) {
        const game = {
          id: `automatic-${season}-${week}-${pair}`,
          season,
          week,
          seasonType: 'REG',
          date: new Date(Date.UTC(season, 8, 13) + (week - 1) * 7 * 86400000)
            .toISOString()
            .slice(0, 10),
          home: teams[pair * 2],
          away: teams[pair * 2 + 1],
          ...(complete ? { homeScore: 24, awayScore: 21 } : {}),
        };
        data.games.push(game);
        if (!complete) continue;
        for (const player of participants) {
          if (![game.home, game.away].includes(player.nflTeam)) continue;
          const stats = Object.fromEntries(footballStatKeys.map((key) => [key, 0]));
          if (player.position === 'QB') {
            stats.passing_yards = player.points / 0.04;
            stats.attempts = 30;
          } else if (player.position === 'RB') {
            stats.rushing_yards = player.points * 10;
            stats.carries = 18;
            stats.targets = 0;
          } else {
            stats.receptions = 5;
            stats.receiving_yards = (player.points - 5) * 10;
            stats.targets = 9;
          }
          data.players.push({
            playerId: player.gsisId,
            name: player.name,
            position: player.position,
            team: player.nflTeam,
            opponent: player.nflTeam === game.home ? game.away : game.home,
            season,
            week,
            seasonType: 'REG',
            gameId: game.id,
            stats,
          });
        }
      }
    }
  return data;
}

